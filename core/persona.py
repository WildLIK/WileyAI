"""Personality and grammatical identity do not depend on the selected voice."""
import re


def local_result(text, gender):
    """Only adapt fixed result prefixes, never quoted notes or model output."""
    if gender == "masculine":
        return text
    feminine = {"Запомнил": "Запомнила", "Создал": "Создала", "Удалил": "Удалила", "Передал": "Передала", "Перенёс": "Перенесла", "Отменил": "Отменила", "Отметил": "Отметила", "Не нашёл": "Не нашла", "Не распознал": "Не распознала"}
    neutral = {"Создал встречу": "Создана встреча", "Создал заметку": "Создана заметка", "Удалил событие": "Удалено событие", "Перенёс встречу": "Перенесена встреча", "Передал браузеру": "Команда передана браузеру", "Передал Windows": "Команда передана Windows", "Запомнил": "Запись сохранена", "Перенёс": "Перенесено:", "Отменил": "Отменено:", "Отметил выполненной задачу": "Выполнена задача", "Не нашёл": "Не удалось найти", "Не распознал": "Не удалось распознать"}
    prefixes = feminine if gender == "feminine" else neutral
    for source, target in prefixes.items():
        changed, count = re.subn(r"^(\d+\. )?" + re.escape(source) + r"\b", lambda match: (match[1] or "") + target, text, count=1)
        if count:
            return changed
    return text


